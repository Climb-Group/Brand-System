"""Build the brand tokens into CSS and SCSS, and check every promised colour pair.

Usage:
    python3 tokens/build_tokens.py                        # check contrast, write tokens.css and _tokens.scss
    python3 tokens/build_tokens.py --check                # check contrast and that the generated files are current
    python3 tokens/build_tokens.py --copy-to PATH.scss    # also write a copy of the SCSS (for a website theme or module)

Exit code 1 when a pair fails its WCAG 2.2 threshold or (with --check) a generated file is stale.
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
SOURCE = HERE / "brand.tokens.json"
CSS_OUT = HERE / "tokens.css"
SCSS_OUT = HERE / "_tokens.scss"
REPO = HERE.parent
HEADER = "Generated by tokens/build_tokens.py from brand.tokens.json. Do not edit."
REF = re.compile(r"^\{([a-z0-9.-]+)\}$")


def load():
    return json.loads(SOURCE.read_text(encoding="utf-8"))


def lookup(tree, path):
    node = tree
    for part in path.split("."):
        node = node[part]
    return node


def resolve(tree, value, seen=()):
    if isinstance(value, str):
        m = REF.match(value)
        if m:
            path = m.group(1)
            if path in seen:
                raise ValueError("token reference loop: %s" % " > ".join(seen + (path,)))
            return resolve(tree, lookup(tree, path)["$value"], seen + (path,))
    return value


def flatten(tree, node=None, prefix=()):
    """Yield (path tuple, resolved value) for every leaf token, skipping the pairs list."""
    node = tree if node is None else node
    for key, child in node.items():
        if key.startswith("$") or key == "pairs" or not isinstance(child, dict):
            continue
        if "$value" in child:
            yield prefix + (key,), resolve(tree, child["$value"])
        else:
            yield from flatten(tree, child, prefix + (key,))


def luminance(hex_colour):
    rgb = [int(hex_colour[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    lin = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def ratio(fg, bg):
    a, b = luminance(fg), luminance(bg)
    return (max(a, b) + 0.05) / (min(a, b) + 0.05)


def check_pairs(tree):
    """Return (rows, failures). Each row is (fg path, fg hex, bg path, bg hex, ratio, need)."""
    need = {"normal": tree["contrast"]["normal-text"]["$value"], "large": tree["contrast"]["large-text"]["$value"],
            "aaa": tree["contrast"]["aaa-text"]["$value"], "aaa-large": tree["contrast"]["aaa-large-text"]["$value"]}
    rows, failures = [], []
    for fg_path, bg_path, kind in tree["pairs"]["$value"]:
        fg = resolve(tree, lookup(tree, fg_path)["$value"])
        bg = resolve(tree, lookup(tree, bg_path)["$value"])
        r = ratio(fg, bg)
        row = (fg_path, fg, bg_path, bg, r, need[kind])
        rows.append(row)
        if r < need[kind]:
            failures.append(row)
    return rows, failures


def css_value(value):
    if isinstance(value, list):
        return ", ".join('"%s"' % v if " " in v else v for v in value)
    return str(value)


def render(tree):
    tokens = list(flatten(tree))
    css = ["/* %s */" % HEADER, ":root {"]
    scss = ["// %s" % HEADER]
    for path, value in tokens:
        if path[0] in ("contrast", "print"):
            continue
        name = "-".join(path).replace("_", "-")
        css.append("    --climb-%s: %s;" % (name, css_value(value)))
        scss.append("$climb-%s: %s;" % (name, css_value(value)))
    css.append("}")
    # Each colour theme as a scope: <body data-climb-theme="aaa-dark"> (or any element) re-points the short names.
    for name, theme in tree.get("theme", {}).items():
        if name.startswith("$"):
            continue
        css.append('[data-climb-theme="%s"] {' % name)
        for role in theme:
            if not role.startswith("$"):
                css.append("    --climb-%s: var(--climb-theme-%s-%s);" % (role, name, role))
        css.append("}")
    # The AAA size variants as one switch: data-climb-size="aaa".
    css.append('[data-climb-size="aaa"] {')
    for key, var in (("type-body-size", "aaa-type-body-size"), ("type-body-line-height", "aaa-type-body-line-height"),
                     ("type-small-size", "aaa-type-small-size"), ("type-eyebrow-size", "aaa-type-eyebrow-size"),
                     ("layout-measure", "aaa-layout-measure"), ("layout-target-min", "aaa-layout-target")):
        css.append("    --climb-%s: var(--climb-%s);" % (key, var))
    css.append("}")
    return "\n".join(css) + "\n", "\n".join(scss) + "\n"


def main(argv):
    tree = load()
    rows, failures = check_pairs(tree)
    for fg_path, fg, bg_path, bg, r, need in rows:
        mark = "ok  " if r >= need else "FAIL"
        print("[tokens] %s %-32s on %-28s %5.2f:1 (needs %.1f)" % (mark, fg_path, bg_path, r, need))
    css, scss = render(tree)
    stale = []
    # A website theme or module can carry its own copy, because some platforms only load assets from inside a module.
    copies = [pathlib.Path(argv[i + 1]).resolve() for i, a in enumerate(argv) if a == "--copy-to" and i + 1 < len(argv)]
    if "--check" in argv:
        for out, text in [(CSS_OUT, css), (SCSS_OUT, scss)] + [(c, scss) for c in copies]:
            if not out.exists() or out.read_text(encoding="utf-8") != text:
                stale.append(str(out))
        for name in stale:
            print("[tokens] STALE %s: run build_tokens.py" % name)
    else:
        CSS_OUT.write_text(css, encoding="utf-8")
        SCSS_OUT.write_text(scss, encoding="utf-8")
        for copy in copies:
            copy.parent.mkdir(parents=True, exist_ok=True)
            copy.write_text(scss, encoding="utf-8")
        print("[tokens] wrote %s" % ", ".join([CSS_OUT.name, SCSS_OUT.name] + [str(c) for c in copies]))
    return 1 if failures or stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
