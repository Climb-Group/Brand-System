// Copies the brand book script into the web part as a module and lists the brand book pages.
// Usage: node scripts/sync-book.mjs <standalone brand book folder>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const book = process.argv[2];
if (!book) {
  console.error("Usage: node scripts/sync-book.mjs <standalone brand book folder>");
  process.exit(1);
}
const out = new URL("../src/webparts/climbBrandPage/book/", import.meta.url).pathname;
let js = readFileSync(join(book, "js/brand_book.js"), "utf8");

// The script runs once per page load on the website. Here it runs when the web part has drawn the page, and four
// places that build addresses ask the web part, because the page is not served from the brand book folder.
const swaps = [
  ['(function () {\n    "use strict";', "export function initBrandBook(hooks) {\n    \"use strict\";"],
  ['iframe.src = iframe.getAttribute("data-src") + "?theme=" + encodeURIComponent(theme());', "hooks.frame(iframe, theme());"],
  ['window.history.replaceState(null, "", window.location.pathname + window.location.hash);', "window.history.replaceState(null, \"\", hooks.withoutBrand());"],
  ["'<img src=\"' + esc(r.preview) + '\"", "'<img src=\"' + esc(hooks.asset(r.preview)) + '\""],
  ["return '<li><a href=\"' + esc(r.url) + '\">'", "return '<li><a href=\"' + esc(hooks.link(r.url)) + '\">'"],
];
for (const [from, to] of swaps) {
  if (!js.includes(from)) {
    console.error("The brand book script changed; update scripts/sync-book.mjs. Not found:\n" + from);
    process.exit(1);
  }
  js = js.replace(from, to);
}
js = js.replace(/\}\)\(\);\s*$/, "}\n");
writeFileSync(join(out, "brandBook.ts"), "/* eslint-disable */\n// @ts-nocheck\n/* Generated by scripts/sync-book.mjs from the brand book. Do not edit. */\n" + js);

const pages = JSON.parse(readFileSync(join(book, "search.json"), "utf8")).pages
  .map((p) => ({ key: p.url.replace(/\.html$/, ""), text: p.title }));
writeFileSync(join(out, "pages.ts"), "// Generated by scripts/sync-book.mjs from the brand book. Do not edit.\n" +
  "export const BRAND_PAGES: { key: string; text: string }[] = " + JSON.stringify(pages, null, 2) + ";\n");
console.log("Synced brand_book.js and " + pages.length + " pages");
