<#
.SYNOPSIS
    Deploys the brand fonts and the Word, Excel and PowerPoint templates to Windows PCs.

.DESCRIPTION
    Creates or updates an Intune remediation (Devices > Scripts and remediations) called
    "Climb - Windows - Brand fonts and Office templates":

      - Detection: is the templates package at the expected version installed?
      - Remediation: download Climb-Templates-<version>.zip from the public release,
        check its SHA-256, unzip it and run windows\Install-ClimbTemplates.ps1 as SYSTEM.

    The installer puts Montserrat and Open Sans in C:\Windows\Fonts, the templates in
    C:\ProgramData\Climb\Templates, and registers an Active Setup step so each person's
    Office points at them at their next sign-in (File > New > Shared or Custom tab).

    Remediations run every day, so when a new templates release comes out you just
    re-run this script: it picks up the new version and every PC updates itself.
    Nothing has to be packaged as .intunewin, so this works from Linux.

    Needs Windows Enterprise E3/E5 per user (included in Microsoft 365 E5). The first
    time remediations are used in a tenant, an Intune admin must confirm licensing once in
    the admin center (Devices > Scripts and remediations).

.PARAMETER TemplatesVersion
    Package version, for example 1.2.2. Default: the latest templates release.
.PARAMETER IncludeVideo
    Also install the DaVinci Resolve and Premiere Pro files. Off by default for the fleet.
.PARAMETER Target
    AllDevices (default), AllUsers, Group or None.
.PARAMETER GroupName
    Entra group name(s) when -Target Group. Try a pilot group first.
.PARAMETER RunAt
    Local time of the daily run. Default 09:00.

.EXAMPLE
    pwsh ./10-Windows-Templates.ps1 -WhatIf
.EXAMPLE
    pwsh ./10-Windows-Templates.ps1 -Target Group -GroupName 'Climb pilot devices'
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [string]$TemplatesVersion,
    [switch]$IncludeVideo,
    [ValidateSet('AllDevices', 'AllUsers', 'Group', 'None')][string]$Target = 'AllDevices',
    [string[]]$GroupName,
    [string]$RunAt = '09:00',
    [string]$TenantId,
    [switch]$UseDeviceCode
)

$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'ClimbIntune.psm1') -Force
Connect-ClimbGraph -TenantId $TenantId -UseDeviceCode:$UseDeviceCode

$release = Get-ClimbTemplatesRelease -Version $TemplatesVersion
Write-ClimbStep "Templates $($release.Version): $($release.Url) (sha256 $($release.Sha256))"

$detect = @"
# Climb brand templates: detection. Generated by 10-Windows-Templates.ps1.
`$Expected = '$($release.Version)'
`$Installed = (Get-ItemProperty -Path 'HKLM:\SOFTWARE\Climb\Templates' -Name 'Version' -ErrorAction SilentlyContinue).Version
if (`$Installed -eq `$Expected -and (Test-Path (Join-Path `$env:ProgramData 'Climb\Templates\Office'))) {
    Write-Output "Climb templates `$Installed installed"
    exit 0
}
Write-Output "Climb templates missing or out of date (found '`$Installed', want '`$Expected')"
exit 1
"@

$skip = if ($IncludeVideo) { '' } else { ' -SkipVideo' }
$remediate = @"
# Climb brand templates: remediation. Generated by 10-Windows-Templates.ps1.
`$ErrorActionPreference = 'Stop'
`$Version = '$($release.Version)'
`$Url = '$($release.Url)'
`$Sha256 = '$($release.Sha256)'
`$Work = Join-Path `$env:ProgramData 'Climb\Download'
try {
    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    New-Item -ItemType Directory -Force -Path `$Work | Out-Null
    `$Zip = Join-Path `$Work "Climb-Templates-`$Version.zip"
    `$ProgressPreference = 'SilentlyContinue'
    Invoke-WebRequest -Uri `$Url -OutFile `$Zip -UseBasicParsing
    `$Hash = (Get-FileHash -Algorithm SHA256 -Path `$Zip).Hash.ToLowerInvariant()
    if (`$Hash -ne `$Sha256) { throw "Checksum mismatch: got `$Hash" }
    `$Dir = Join-Path `$Work "Climb-Templates-`$Version"
    if (Test-Path `$Dir) { Remove-Item `$Dir -Recurse -Force }
    Expand-Archive -Path `$Zip -DestinationPath `$Work -Force
    & "`$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" -NoProfile -ExecutionPolicy Bypass -File (Join-Path `$Dir 'windows\Install-ClimbTemplates.ps1')$skip | Out-Null
    `$code = `$LASTEXITCODE
    Remove-Item `$Zip -Force -ErrorAction SilentlyContinue
    Remove-Item `$Dir -Recurse -Force -ErrorAction SilentlyContinue
    if (`$code -and `$code -ne 0) { throw "Installer exited with `$code" }
    Write-Output "Installed Climb templates `$Version"
    exit 0
} catch {
    Write-Output "Climb templates install failed: `$(`$_.Exception.Message)"
    exit 1
}
"@

$name = Get-ClimbName 'Windows - Brand fonts and Office templates'
$body = @{
    '@odata.type'            = '#microsoft.graph.deviceHealthScript'
    displayName              = $name
    description              = "Installs Montserrat and Open Sans and the ClimbUK, ClimbGroup and Climb27 Word, Excel and PowerPoint templates (package $($release.Version)). Managed by the Climb Intune scripts: re-run 10-Windows-Templates.ps1 to change it."
    publisher                = 'ClimbGroup'
    runAsAccount             = 'system'
    runAs32Bit               = $false
    enforceSignatureCheck    = $false
    detectionScriptContent   = ConvertTo-ClimbBase64 $detect
    remediationScriptContent = ConvertTo-ClimbBase64 $remediate
    roleScopeTagIds          = @('0')
}

# Resolve the assignment first, so a missing group stops the run before anything is created.
$targets = Get-ClimbAssignmentTargets -Target $Target -GroupName $GroupName
$id = Set-ClimbObject -Collection 'deviceManagement/deviceHealthScripts' -Name $name -Body $body -WhatIf:$WhatIfPreference

$time = [timespan]::Parse($RunAt).ToString('hh\:mm\:ss')
$schedule = @{ '@odata.type' = '#microsoft.graph.deviceHealthScriptDailySchedule'; interval = 1; useUtc = $false; time = $time }
Set-ClimbAssignment -Collection 'deviceManagement/deviceHealthScripts' -Id $id -Name $name -Kind healthScript -Targets $targets -RunSchedule $schedule -WhatIf:$WhatIfPreference

Write-ClimbStep 'Done. PCs pick this up at their next Intune check-in; check Devices > Scripts and remediations for status.'
