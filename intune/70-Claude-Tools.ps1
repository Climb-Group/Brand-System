$targets = Get-ClimbAssignmentTargets -Target $Target -GroupName $GroupName

# --- 1. Windows: Claude app and Git (system) -----------------------------------------
$detect1 = @'
# Climb Claude app and Git: detection. Generated by 70-Claude-Tools.ps1.
$claude = Get-AppxProvisionedPackage -Online | Where-Object { $_.DisplayName -like '*Claude*' }
$codex = Get-AppxProvisionedPackage -Online | Where-Object { $_.DisplayName -like '*ChatGPT*' -or $_.DisplayName -like '*OpenAI*' }
$git = Test-Path (Join-Path $env:ProgramFiles 'Git\cmd\git.exe')
if ($claude -and $codex -and $git) { Write-Output 'Claude app, ChatGPT and Codex app and Git installed'; exit 0 }
Write-Output "Missing: $(if (-not $claude) { 'Claude app ' })$(if (-not $codex) { 'ChatGPT and Codex app ' })$(if (-not $git) { 'Git' })"
