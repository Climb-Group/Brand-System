<#
.SYNOPSIS
    Installs Claude, Claude Code, Python, graphify and a copy of the brand system on every device.

.DESCRIPTION
    Creates or updates four Intune objects. Everything they install updates itself, and the
    daily runs keep the brand system copy current, so nothing needs managing afterwards.

    Windows:
      1. Remediation "Climb - Windows - Claude app and Git" (system, daily): installs the Claude
         desktop app for every person (MSIX, provisioned) and Git for Windows when missing.
         The Claude app updates itself.
      2. Remediation "Climb - Windows - Claude Code and brand tools" (signed-in person, daily):
         installs Claude Code (updates itself), uv, Python 3.13, then clones the brand system to
         %USERPROFILE%\Climb\Brand-System, pulls new commits every day and sets up graphify.

    macOS:
      3. Shell script "Climb - macOS - Claude app and Git" (root, daily): installs the Claude
         desktop app (updates itself) and the Apple Command Line Tools, which bring git.
      4. Shell script "Climb - macOS - Claude Code and brand tools" (signed-in person, daily):
         the same as 2, into ~/Climb/Brand-System.

    The brand system copy is a git clone of the public repository: brand tools such as
    python3 .agents/skills/climb-voice/scripts/check_copy.py run from it, and graphify
    queries its committed graph. graphify is set up without its git hooks, so the copy stays
    clean. The daily pull only fast-forwards; a copy with local edits is fetched but left alone.

    The person-level scripts also set up graphify for agents:
      - A personal preferences graph, local only: a preferences.md file in the person's local
        app data folder (climb-preferences), indexed and registered next to the brand system
        graph with graphify global add, so one graph answers for both.
      - An always-on graphify MCP server over that combined graph, started at login (a
        LaunchAgent on macOS, a logon scheduled task on Windows). It listens on 127.0.0.1 only
        and needs a key made for each person and readable only by them. Claude Code is
        registered with it; the Claude app, which takes local servers it starts itself, gets
        the same graph over stdio.

.PARAMETER RepoUrl
    Default https://github.com/Climb-Group/Brand-System.git.
.PARAMETER PythonVersion
    Default 3.13.
.PARAMETER McpPort
    Local port for the graphify MCP server. Default 8765.
.PARAMETER Target
    AllDevices (default), AllUsers, Group or None.
.PARAMETER GroupName
    Entra group name(s) when -Target Group.

.EXAMPLE
    pwsh ./70-Claude-Tools.ps1 -WhatIf
#>
[CmdletBinding(SupportsShouldProcess)]
param(
