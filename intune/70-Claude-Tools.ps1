<#
.SYNOPSIS
    Installs Claude, Claude Code, Python, graphify and a copy of the brand system on every device.

.DESCRIPTION
    Creates or updates four Intune objects. Everything they install updates itself, and the
    daily runs keep the brand system copy current, so nothing needs managing afterwards.

    Windows:
      1. Remediation "Climb - Windows - Claude app and Git" (system, daily): installs the Claude
         desktop app for every person (MSIX, provisioned) and Git for Windows when missing.
         The Claude app updates itself.
      2. Remediation "Climb - Windows - Claude Code and brand tools" (signed-in person, daily):
         installs Claude Code (updates itself), uv, Python 3.13, then clones the brand system to
         %USERPROFILE%\Climb\Brand-System, pulls new commits every day and sets up graphify.

    macOS:
      3. Shell script "Climb - macOS - Claude app and Git" (root, daily): installs the Claude
         desktop app (updates itself) and the Apple Command Line Tools, which bring git.
      4. Shell script "Climb - macOS - Claude Code and brand tools" (signed-in person, daily):
         the same as 2, into ~/Climb/Brand-System.

    The brand system copy is a git clone of the public repository: brand tools such as
    python3 .agents/skills/climb-voice/scripts/check_copy.py run from it, and graphify
    queries its committed graph. graphify is set up without its git hooks, so the copy stays
    clean. The daily pull only fast-forwards; a copy with local edits is fetched but left alone.

.PARAMETER RepoUrl
    Default https://github.com/Climb-Group/Brand-System.git.
.PARAMETER PythonVersion
    Default 3.13.
.PARAMETER Target
    AllDevices (default), AllUsers, Group or None.
.PARAMETER GroupName
    Entra group name(s) when -Target Group.

.EXAMPLE
    pwsh ./70-Claude-Tools.ps1 -WhatIf
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [string]$RepoUrl = 'https://github.com/Climb-Group/Brand-System.git',
    [string]$PythonVersion = '3.13',
    [ValidateSet('AllDevices', 'AllUsers', 'Group', 'None')][string]$Target = 'AllDevices',
    [string[]]$GroupName,
    [string]$TenantId,
    [switch]$UseDeviceCode
)

$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'ClimbIntune.psm1') -Force
Connect-ClimbGraph -TenantId $TenantId -UseDeviceCode:$UseDeviceCode
$targets = Get-ClimbAssignmentTargets -Target $Target -GroupName $GroupName

# --- 1. Windows: Claude app and Git (system) -----------------------------------------
$detect1 = @'
# Climb Claude app and Git: detection. Generated by 70-Claude-Tools.ps1.
$claude = Get-AppxProvisionedPackage -Online | Where-Object { $_.DisplayName -like '*Claude*' }
$git = Test-Path (Join-Path $env:ProgramFiles 'Git\cmd\git.exe')
if ($claude -and $git) { Write-Output 'Claude app and Git installed'; exit 0 }
Write-Output "Missing: $(if (-not $claude) { 'Claude app ' })$(if (-not $git) { 'Git' })"
exit 1
'@
$remediate1 = @'
# Climb Claude app and Git: remediation. Generated by 70-Claude-Tools.ps1.
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
$arm = $env:PROCESSOR_ARCHITECTURE -eq 'ARM64'
$work = Join-Path $env:ProgramData 'Climb\Download'
New-Item -ItemType Directory -Force -Path $work | Out-Null
try {
    if (-not (Get-AppxProvisionedPackage -Online | Where-Object { $_.DisplayName -like '*Claude*' })) {
        $arch = if ($arm) { 'arm64' } else { 'x64' }
        $msix = Join-Path $work 'Claude.msix'
        Invoke-WebRequest -Uri "https://claude.ai/api/desktop/win32/$arch/msix/latest/redirect" -OutFile $msix -UseBasicParsing
        $sig = Get-AuthenticodeSignature -FilePath $msix
        if ($sig.Status -ne 'Valid' -or $sig.SignerCertificate.Subject -notlike '*Anthropic*') { throw "Claude.msix signature: $($sig.Status) $($sig.SignerCertificate.Subject)" }
        Add-AppxProvisionedPackage -Online -PackagePath $msix -SkipLicense -Regions 'all' | Out-Null
        Remove-Item $msix -Force
        Write-Output 'Installed the Claude app for every person'
    }
    if (-not (Test-Path (Join-Path $env:ProgramFiles 'Git\cmd\git.exe'))) {
        $release = Invoke-RestMethod -Uri 'https://api.github.com/repos/git-for-windows/git/releases/latest' -Headers @{ 'User-Agent' = 'climb-intune' }
        $pattern = if ($arm) { '^Git-[\d.]+-arm64\.exe$' } else { '^Git-[\d.]+-64-bit\.exe$' }
        $asset = $release.assets | Where-Object { $_.name -match $pattern } | Select-Object -First 1
        if (-not $asset) { throw "No Git installer matching $pattern in $($release.tag_name)" }
        $exe = Join-Path $work $asset.name
        Invoke-WebRequest -Uri $asset.browser_download_url -OutFile $exe -UseBasicParsing
        $sig = Get-AuthenticodeSignature -FilePath $exe
        if ($sig.Status -ne 'Valid') { throw "Git installer signature: $($sig.Status)" }
        $p = Start-Process -FilePath $exe -ArgumentList '/VERYSILENT', '/NORESTART', '/NOCANCEL', '/SP-', '/SUPPRESSMSGBOXES' -Wait -PassThru
        Remove-Item $exe -Force
        if ($p.ExitCode -ne 0) { throw "Git installer exited with $($p.ExitCode)" }
        Write-Output "Installed Git $($release.tag_name)"
    }
    exit 0
} catch {
    Write-Output "Install failed: $($_.Exception.Message)"
    exit 1
}
'@

# --- 2. Windows: Claude Code and brand tools (signed-in person) -------------------------
$common2 = @"
`$RepoUrl = '$($RepoUrl.Replace("'", "''"))'
`$Python = '$PythonVersion'
`$Dest = Join-Path `$env:USERPROFILE 'Climb\Brand-System'
`$Bin = Join-Path `$env:USERPROFILE '.local\bin'
`$Graphify = Join-Path `$env:USERPROFILE '.local\share\resnovas-graphify\bin\graphify.exe'
`$env:Path = "`$Bin;`$env:ProgramFiles\Git\cmd;`$env:Path"
"@
$detect2 = @"
# Climb Claude Code and brand tools: detection. Generated by 70-Claude-Tools.ps1.
$common2
`$missing = @()
if (-not (Test-Path (Join-Path `$Bin 'claude.exe'))) { `$missing += 'Claude Code' }
if (-not (Test-Path (Join-Path `$Bin 'uv.exe'))) { `$missing += 'uv' }
if (-not (Test-Path (Join-Path `$Bin 'python.exe'))) { `$missing += 'Python' }
if (-not (Test-Path `$Graphify)) { `$missing += 'graphify' }
`$fetch = Join-Path `$Dest '.git\FETCH_HEAD'
if (-not (Test-Path `$fetch) -or ((Get-Date) - (Get-Item `$fetch).LastWriteTime).TotalHours -gt 20) { `$missing += 'brand system update' }
if (`$missing) { Write-Output "To do: `$(`$missing -join ', ')"; exit 1 }
Write-Output 'Claude Code, Python, graphify and the brand system are current'
exit 0
"@
$remediate2 = @"
# Climb Claude Code and brand tools: remediation. Generated by 70-Claude-Tools.ps1.
$common2
`$ProgressPreference = 'SilentlyContinue'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
`$failed = @()
# Claude Code and uv install per person and update themselves.
if (-not (Test-Path (Join-Path `$Bin 'claude.exe'))) {
    try { Invoke-RestMethod https://claude.ai/install.ps1 | Invoke-Expression } catch { `$failed += "Claude Code: `$(`$_.Exception.Message)" }
}
if (-not (Test-Path (Join-Path `$Bin 'uv.exe'))) {
    try { `$env:UV_INSTALL_DIR = `$Bin; Invoke-RestMethod https://astral.sh/uv/install.ps1 | Invoke-Expression } catch { `$failed += "uv: `$(`$_.Exception.Message)" }
} else { & (Join-Path `$Bin 'uv.exe') self update 2>&1 | Out-Null }
if (Test-Path (Join-Path `$Bin 'uv.exe')) {
    & (Join-Path `$Bin 'uv.exe') python install `$Python --default 2>&1 | Out-Null
    if (`$LASTEXITCODE) { `$failed += 'Python install' }
}
`$git = Join-Path `$env:ProgramFiles 'Git\cmd\git.exe'
if (-not (Test-Path `$git)) { Write-Output 'Git is not installed yet; the system remediation adds it'; exit 1 }
if (-not (Test-Path (Join-Path `$Dest '.git'))) {
    New-Item -ItemType Directory -Force -Path (Split-Path `$Dest) | Out-Null
    & `$git clone --filter=blob:none `$RepoUrl `$Dest 2>&1 | Out-Null
    if (`$LASTEXITCODE) { `$failed += 'brand system clone' }
} else {
    & `$git -C `$Dest fetch --quiet origin 2>&1 | Out-Null
    `$branch = & `$git -C `$Dest rev-parse --abbrev-ref HEAD
    `$dirty = & `$git -C `$Dest status --porcelain --untracked-files=no
    if (`$branch -eq 'main' -and -not `$dirty) { & `$git -C `$Dest merge --ff-only --quiet origin/main 2>&1 | Out-Null }
    else { Write-Output "Brand system has local changes or is on `$branch; fetched only" }
}
if (-not (Test-Path `$Graphify) -and (Test-Path (Join-Path `$Dest 'tools\graphify\graphify'))) {
    Push-Location `$Dest
    & (Join-Path `$env:ProgramFiles 'Git\bin\sh.exe') tools/graphify/graphify setup --no-hooks 2>&1 | Out-Null
    if (`$LASTEXITCODE) { `$failed += 'graphify setup' }
    Pop-Location
}
if (`$failed) { Write-Output "Failed: `$(`$failed -join '; ')"; exit 1 }
Write-Output "Claude Code, Python `$Python, graphify and the brand system at `$Dest are current"
exit 0
"@

# --- 3. macOS: Claude app and Command Line Tools (root) --------------------------------
$mac3 = @(
    '#!/bin/bash'
    '# Climb Claude app and git for macOS. Generated by 70-Claude-Tools.ps1.'
    'set -uo pipefail'
    'LOG="/Library/Logs/Climb/claude-app.log"'
    'mkdir -p "$(dirname "$LOG")"'
    'exec >>"$LOG" 2>&1'
    'echo "$(date -u +%FT%TZ) checking the Claude app and git"'
    'if [ ! -d "/Applications/Claude.app" ]; then'
    '  WORK="$(mktemp -d /tmp/climb-claude.XXXXXX)"'
    '  curl -fsSL --retry 3 -o "$WORK/Claude.pkg" "https://claude.ai/api/desktop/darwin/universal/pkg/latest/redirect"'
    '  if pkgutil --check-signature "$WORK/Claude.pkg" | grep -q "Anthropic"; then'
    '    installer -pkg "$WORK/Claude.pkg" -target / && echo "installed the Claude app"'
    '  else'
    '    echo "Claude.pkg is not signed by Anthropic; not installed"'
    '  fi'
    '  rm -rf "$WORK"'
    'fi'
    '# git comes with the Apple Command Line Tools.'
    'if ! xcode-select -p >/dev/null 2>&1; then'
    '  FLAG=/tmp/.com.apple.dt.CommandLineTools.installondemand.in-progress'
    '  touch "$FLAG"'
    '  LABEL="$(softwareupdate -l 2>/dev/null | sed -n ''s/^\* Label: \(Command Line Tools.*\)$/\1/p'' | sort -V | tail -n1)"'
    '  if [ -n "$LABEL" ]; then softwareupdate -i "$LABEL" && echo "installed $LABEL"; else echo "Command Line Tools not offered by Software Update yet"; fi'
    '  rm -f "$FLAG"'
    'fi'
    'echo "done"'
)

# --- 4. macOS: Claude Code and brand tools (signed-in person) ---------------------------
$mac4 = @(
    '#!/bin/bash'
    '# Climb Claude Code and brand tools for macOS. Generated by 70-Claude-Tools.ps1.'
    'set -uo pipefail'
    "REPO_URL='$($RepoUrl.Replace("'", "'\''"))'"
    "PYTHON='$PythonVersion'"
    'DEST="$HOME/Climb/Brand-System"'
    'export PATH="$HOME/.local/bin:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"'
    'LOG="$HOME/Library/Logs/Climb/claude-tools.log"'
    'mkdir -p "$(dirname "$LOG")"'
    'exec >>"$LOG" 2>&1'
    'echo "$(date -u +%FT%TZ) checking Claude Code and brand tools"'
    'FAILED=""'
    '# Claude Code and uv install per person and update themselves.'
    '[ -x "$HOME/.local/bin/claude" ] || curl -fsSL https://claude.ai/install.sh | bash || FAILED="$FAILED claude-code"'
    'if [ -x "$HOME/.local/bin/uv" ]; then uv self update || true'
    'else curl -LsSf https://astral.sh/uv/install.sh | env UV_INSTALL_DIR="$HOME/.local/bin" sh || FAILED="$FAILED uv"; fi'
    'if [ -x "$HOME/.local/bin/uv" ]; then uv python install "$PYTHON" --default || FAILED="$FAILED python"; fi'
    'if ! xcode-select -p >/dev/null 2>&1; then echo "git not ready yet (Command Line Tools)"; exit 0; fi'
    'if [ ! -d "$DEST/.git" ]; then'
    '  mkdir -p "$(dirname "$DEST")"'
    '  git clone --filter=blob:none "$REPO_URL" "$DEST" || FAILED="$FAILED clone"'
    'else'
    '  git -C "$DEST" fetch --quiet origin || FAILED="$FAILED fetch"'
    '  if [ "$(git -C "$DEST" rev-parse --abbrev-ref HEAD)" = main ] && [ -z "$(git -C "$DEST" status --porcelain --untracked-files=no)" ]; then'
    '    git -C "$DEST" merge --ff-only --quiet origin/main || FAILED="$FAILED pull"'
    '  else echo "brand system has local changes or is not on main; fetched only"; fi'
    'fi'
    'if [ ! -x "$HOME/.local/share/resnovas-graphify/bin/graphify" ] && [ -f "$DEST/tools/graphify/graphify" ]; then'
    '  (cd "$DEST" && sh tools/graphify/graphify setup --no-hooks) || FAILED="$FAILED graphify"'
    'fi'
    'if [ -n "$FAILED" ]; then echo "failed:$FAILED"; exit 1; fi'
    'echo "Claude Code, Python $PYTHON, graphify and the brand system at $DEST are current"'
)

# --- Write the objects --------------------------------------------------------------
$daily = @{ '@odata.type' = '#microsoft.graph.deviceHealthScriptDailySchedule'; interval = 1; useUtc = $false; time = '11:00:00' }
$items = @(
    @{ Collection = 'deviceManagement/deviceHealthScripts'; Kind = 'healthScript'; Name = Get-ClimbName 'Windows - Claude app and Git'
        Body = @{ '@odata.type' = '#microsoft.graph.deviceHealthScript'
            description = 'Installs the Claude desktop app for every person and Git for Windows. Managed by 70-Claude-Tools.ps1.'
            publisher = 'ClimbGroup'; runAsAccount = 'system'; runAs32Bit = $false; enforceSignatureCheck = $false
            detectionScriptContent = ConvertTo-ClimbBase64 $detect1; remediationScriptContent = ConvertTo-ClimbBase64 $remediate1; roleScopeTagIds = @('0') } }
    @{ Collection = 'deviceManagement/deviceHealthScripts'; Kind = 'healthScript'; Name = Get-ClimbName 'Windows - Claude Code and brand tools'
        Body = @{ '@odata.type' = '#microsoft.graph.deviceHealthScript'
            description = 'Installs Claude Code, uv, Python and graphify for the signed-in person and keeps a copy of the brand system current. Managed by 70-Claude-Tools.ps1.'
            publisher = 'ClimbGroup'; runAsAccount = 'user'; runAs32Bit = $false; enforceSignatureCheck = $false
            detectionScriptContent = ConvertTo-ClimbBase64 $detect2; remediationScriptContent = ConvertTo-ClimbBase64 $remediate2; roleScopeTagIds = @('0') } }
    @{ Collection = 'deviceManagement/deviceShellScripts'; Kind = 'shellScript'; Name = Get-ClimbName 'macOS - Claude app and Git'
        Body = @{ '@odata.type' = '#microsoft.graph.deviceShellScript'
            description = 'Installs the Claude desktop app and the Command Line Tools (git). Log: /Library/Logs/Climb/claude-app.log. Managed by 70-Claude-Tools.ps1.'
            fileName = 'climb-claude-app.sh'; scriptContent = ConvertTo-ClimbBase64 (($mac3 -join "`n") + "`n")
            runAsAccount = 'system'; executionFrequency = 'P1D'; retryCount = 3; blockExecutionNotifications = $true; roleScopeTagIds = @('0') } }
    @{ Collection = 'deviceManagement/deviceShellScripts'; Kind = 'shellScript'; Name = Get-ClimbName 'macOS - Claude Code and brand tools'
        Body = @{ '@odata.type' = '#microsoft.graph.deviceShellScript'
            description = 'Installs Claude Code, uv, Python and graphify for the signed-in person and keeps a copy of the brand system current. Log: ~/Library/Logs/Climb/claude-tools.log. Managed by 70-Claude-Tools.ps1.'
            fileName = 'climb-claude-tools.sh'; scriptContent = ConvertTo-ClimbBase64 (($mac4 -join "`n") + "`n")
            runAsAccount = 'user'; executionFrequency = 'P1D'; retryCount = 3; blockExecutionNotifications = $true; roleScopeTagIds = @('0') } }
)

foreach ($i in $items) {
    $i.Body.displayName = $i.Name
    $id = Set-ClimbObject -Collection $i.Collection -Name $i.Name -Body $i.Body -WhatIf:$WhatIfPreference
    $assign = @{ Collection = $i.Collection; Id = $id; Name = $i.Name; Kind = $i.Kind; Targets = $targets; WhatIf = $WhatIfPreference }
    if ($i.Kind -eq 'healthScript') { $assign.RunSchedule = $daily }
    Set-ClimbAssignment @assign
}

Write-ClimbStep 'Done. Devices install at their next daily run; the person-level steps wait until git is installed.'
