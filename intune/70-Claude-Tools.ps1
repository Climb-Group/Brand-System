'@
$remediate1 = @'
# Climb Claude app and Git: remediation. Generated by 70-Claude-Tools.ps1.
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
$arm = $env:PROCESSOR_ARCHITECTURE -eq 'ARM64'
$work = Join-Path $env:ProgramData 'Climb\Download'
New-Item -ItemType Directory -Force -Path $work | Out-Null
try {
    if (-not (Get-AppxProvisionedPackage -Online | Where-Object { $_.DisplayName -like '*Claude*' })) {
        $arch = if ($arm) { 'arm64' } else { 'x64' }
        $msix = Join-Path $work 'Claude.msix'
        Invoke-WebRequest -Uri "https://claude.ai/api/desktop/win32/$arch/msix/latest/redirect" -OutFile $msix -UseBasicParsing
        $sig = Get-AuthenticodeSignature -FilePath $msix
        if ($sig.Status -ne 'Valid' -or $sig.SignerCertificate.Subject -notlike '*Anthropic*') { throw "Claude.msix signature: $($sig.Status) $($sig.SignerCertificate.Subject)" }
        Add-AppxProvisionedPackage -Online -PackagePath $msix -SkipLicense -Regions 'all' | Out-Null
        Remove-Item $msix -Force
        Write-Output 'Installed the Claude app for every person'
    }
    # The ChatGPT desktop app holds Codex; it updates itself.
    if (-not (Get-AppxProvisionedPackage -Online | Where-Object { $_.DisplayName -like '*ChatGPT*' -or $_.DisplayName -like '*OpenAI*' })) {
        $arch = if ($arm) { 'arm64' } else { 'x64' }
        $msix = Join-Path $work 'ChatGPT.msix'
        $license = Join-Path $work 'ChatGPT-License.xml'
        Invoke-WebRequest -Uri "https://persistent.oaistatic.com/codex-app-prod/ChatGPT-$arch.msix" -OutFile $msix -UseBasicParsing
        Invoke-WebRequest -Uri 'https://persistent.oaistatic.com/codex-app-prod/ChatGPT-License.xml' -OutFile $license -UseBasicParsing
        $sig = Get-AuthenticodeSignature -FilePath $msix
        if ($sig.Status -ne 'Valid' -or $sig.SignerCertificate.Subject -notlike '*OpenAI*') { throw "ChatGPT.msix signature: $($sig.Status) $($sig.SignerCertificate.Subject)" }
        Add-AppxProvisionedPackage -Online -PackagePath $msix -LicensePath $license -Regions 'all' | Out-Null
        Remove-Item $msix, $license -Force
        Write-Output 'Installed the ChatGPT and Codex app for every person'
    }
    if (-not (Test-Path (Join-Path $env:ProgramFiles 'Git\cmd\git.exe'))) {
        $release = Invoke-RestMethod -Uri 'https://api.github.com/repos/git-for-windows/git/releases/latest' -Headers @{ 'User-Agent' = 'climb-intune' }
        $pattern = if ($arm) { '^Git-[\d.]+-arm64\.exe$' } else { '^Git-[\d.]+-64-bit\.exe$' }
        $asset = $release.assets | Where-Object { $_.name -match $pattern } | Select-Object -First 1
        if (-not $asset) { throw "No Git installer matching $pattern in $($release.tag_name)" }
        $exe = Join-Path $work $asset.name
        Invoke-WebRequest -Uri $asset.browser_download_url -OutFile $exe -UseBasicParsing
        $sig = Get-AuthenticodeSignature -FilePath $exe
        if ($sig.Status -ne 'Valid') { throw "Git installer signature: $($sig.Status)" }
        $p = Start-Process -FilePath $exe -ArgumentList '/VERYSILENT', '/NORESTART', '/NOCANCEL', '/SP-', '/SUPPRESSMSGBOXES' -Wait -PassThru
        Remove-Item $exe -Force
        if ($p.ExitCode -ne 0) { throw "Git installer exited with $($p.ExitCode)" }
        Write-Output "Installed Git $($release.tag_name)"
    }
    exit 0
} catch {
    Write-Output "Install failed: $($_.Exception.Message)"
    exit 1
}
'@

