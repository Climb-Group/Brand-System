<#
.SYNOPSIS
    Makes a Climb brand the default for new blank Word, Excel and PowerPoint files on Windows.

.DESCRIPTION
    Creates or updates an Intune remediation called "Climb - Windows - Office brand defaults"
    that runs as the signed-in person every day:

      - Detection: has this person got this brand and templates version as their default?
      - Remediation: run C:\ProgramData\Climb\Templates\Set-ClimbDefaultsUser.ps1, which puts
        the brand Normal.dotm (letterhead), Blank.potx and Book.xltx in their Office folders.
        Their old Normal.dotm is kept as Normal-before-Climb.dotm.

    Needs 10-Windows-Templates.ps1 with templates package 1.4.0 or later, which installs the
    default files. While Word is open the remediation leaves the files alone and tries the next day.

.PARAMETER Brand
    ClimbGroup (default), ClimbUK or Climb27.
.PARAMETER Target
    AllDevices (default), AllUsers, Group or None.
.PARAMETER GroupName
    Entra group name(s) when -Target Group.
.PARAMETER RunAt
    Local time of the daily run. Default 12:30, when Word is less likely to be open than at 09:00.

.EXAMPLE
    pwsh ./12-Windows-Office-Defaults.ps1 -WhatIf
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [ValidateSet('ClimbUK', 'ClimbGroup', 'Climb27')][string]$Brand = 'ClimbGroup',
    [ValidateSet('AllDevices', 'AllUsers', 'Group', 'None')][string]$Target = 'AllDevices',
    [string[]]$GroupName,
    [string]$RunAt = '12:30',
    [string]$TenantId,
    [switch]$UseDeviceCode
)

$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'ClimbIntune.psm1') -Force
Connect-ClimbGraph -TenantId $TenantId -UseDeviceCode:$UseDeviceCode

$detect = @"
# Climb Office brand defaults: detection. Generated by 12-Windows-Office-Defaults.ps1.
`$Brand = '$Brand'
`$Dest = Join-Path `$env:ProgramData 'Climb\Templates'
`$Version = Get-Content -Path (Join-Path `$Dest 'VERSION') -ErrorAction SilentlyContinue | Select-Object -First 1
if (-not (Test-Path (Join-Path `$Dest "Defaults\`$Brand\Normal.dotm"))) {
    Write-Output 'Climb templates 1.4.0 or later not installed yet'
    exit 0
}
`$Applied = (Get-ItemProperty -Path 'HKCU:\Software\Climb\OfficeDefaults' -Name 'Applied' -ErrorAction SilentlyContinue).Applied
if (`$Applied -eq "`$Version `$Brand") { Write-Output "Office defaults set (`$Applied)"; exit 0 }
Write-Output "Office defaults not set (found '`$Applied', want '`$Version `$Brand')"
exit 1
"@

$remediate = @"
# Climb Office brand defaults: remediation. Generated by 12-Windows-Office-Defaults.ps1.
`$Script = Join-Path `$env:ProgramData 'Climb\Templates\Set-ClimbDefaultsUser.ps1'
if (-not (Test-Path `$Script)) { Write-Output 'Climb templates not installed'; exit 1 }
& `$Script -Brand '$Brand'
exit `$LASTEXITCODE
"@

$name = Get-ClimbName 'Windows - Office brand defaults'
$body = @{
    '@odata.type'            = '#microsoft.graph.deviceHealthScript'
    displayName              = $name
    description              = "New blank Word documents open on the $Brand letterhead; new decks and workbooks use the $Brand master, theme and fonts. Runs as the signed-in person. Managed by 12-Windows-Office-Defaults.ps1."
    publisher                = 'ClimbGroup'
    runAsAccount             = 'user'
    runAs32Bit               = $false
    enforceSignatureCheck    = $false
    detectionScriptContent   = ConvertTo-ClimbBase64 $detect
    remediationScriptContent = ConvertTo-ClimbBase64 $remediate
    roleScopeTagIds          = @('0')
}

# Resolve the assignment first, so a missing group stops the run before anything is created.
$targets = Get-ClimbAssignmentTargets -Target $Target -GroupName $GroupName
$id = Set-ClimbObject -Collection 'deviceManagement/deviceHealthScripts' -Name $name -Body $body -WhatIf:$WhatIfPreference

$time = [timespan]::Parse($RunAt).ToString('hh\:mm\:ss')
$schedule = @{ '@odata.type' = '#microsoft.graph.deviceHealthScriptDailySchedule'; interval = 1; useUtc = $false; time = $time }
Set-ClimbAssignment -Collection 'deviceManagement/deviceHealthScripts' -Id $id -Name $name -Kind healthScript -Targets $targets -RunSchedule $schedule -WhatIf:$WhatIfPreference

Write-ClimbStep "Done. Each person gets the $Brand defaults at the first daily run after the templates are installed."
