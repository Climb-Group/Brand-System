<#
.SYNOPSIS
    Sets the brand desktop picture on Macs.

.DESCRIPTION
    macOS can only point the desktop at a file that is already on the Mac, so this makes two
    Intune objects, the way Microsoft's macOS guide describes:

      1. Shell script "Climb - macOS - Download brand wallpaper": runs as root daily and
         downloads the picture to /Library/Desktop Pictures/Climb/.
      2. Custom profile "Climb - macOS - Desktop picture": a com.apple.desktop payload whose
         override-picture-path points at that file. While it applies, people cannot change
         the desktop picture. Skip it with -DownloadOnly to just make the picture available
         in System Settings > Wallpaper.

    macOS has no managed lock screen picture: the lock screen shows the desktop picture.

.PARAMETER Brand
    ClimbUK (default), ClimbGroup or Climb27.
.PARAMETER Design
    stage-light (default), ascent, connections or contours.
.PARAMETER Size
    2560x1440, 3840x2160 or 5120x2880 (default, sharp on Retina displays).
.PARAMETER ImageUrl
    Use this exact HTTPS image URL instead of a brand centre wallpaper.
.PARAMETER DownloadOnly
    Only download the picture; do not enforce it.

.EXAMPLE
    pwsh ./21-macOS-Wallpaper.ps1 -WhatIf
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [ValidateSet('ClimbUK', 'ClimbGroup', 'Climb27')][string]$Brand = 'ClimbUK',
    [ValidateSet('stage-light', 'ascent', 'connections', 'contours')][string]$Design = 'stage-light',
    [ValidateSet('2560x1440', '3840x2160', '5120x2880')][string]$Size = '5120x2880',
    [string]$ImageUrl,
    [switch]$DownloadOnly,
    [ValidateSet('AllDevices', 'AllUsers', 'Group', 'None')][string]$Target = 'AllDevices',
    [string[]]$GroupName,
    [string]$TenantId,
    [switch]$UseDeviceCode
)

$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'ClimbIntune.psm1') -Force
Connect-ClimbGraph -TenantId $TenantId -UseDeviceCode:$UseDeviceCode

$file = Get-ClimbWallpaperFile -Brand $Brand -Design $Design -Kind desktop -Size $Size
if (-not $ImageUrl) { $ImageUrl = Get-ClimbBrandFileUrl $file }
else { $file = [IO.Path]::GetFileName(([uri]$ImageUrl).AbsolutePath) }
$localPath = "/Library/Desktop Pictures/Climb/$file"
Write-ClimbStep "Picture: $ImageUrl -> $localPath"

$targets = Get-ClimbAssignmentTargets -Target $Target -GroupName $GroupName

# 1. Download script
$lines = @(
    '#!/bin/bash'
    '# Climb brand wallpaper download. Generated by 21-macOS-Wallpaper.ps1.'
    'set -euo pipefail'
    "URL='$ImageUrl'"
    "DEST='$localPath'"
    'mkdir -p "$(dirname "$DEST")"'
    'TMP="$(mktemp /tmp/climb-wallpaper.XXXXXX)"'
    'curl -fsSL --retry 3 -o "$TMP" "$URL"'
    'if ! cmp -s "$TMP" "$DEST" 2>/dev/null; then mv -f "$TMP" "$DEST"; chmod 644 "$DEST"; else rm -f "$TMP"; fi'
    'echo "wallpaper ready at $DEST"'
)
$script = ($lines -join "`n") + "`n"
$scriptName = Get-ClimbName 'macOS - Download brand wallpaper'
$scriptBody = @{
    '@odata.type'               = '#microsoft.graph.deviceShellScript'
    displayName                 = $scriptName
    description                 = "Downloads the $Brand $Design wallpaper to $localPath. Managed by 21-macOS-Wallpaper.ps1."
    fileName                    = 'climb-wallpaper.sh'
    scriptContent               = ConvertTo-ClimbBase64 $script
    runAsAccount                = 'system'
    executionFrequency          = 'P1D'
    retryCount                  = 3
    blockExecutionNotifications = $true
    roleScopeTagIds             = @('0')
}
$scriptId = Set-ClimbObject -Collection 'deviceManagement/deviceShellScripts' -Name $scriptName -Body $scriptBody -WhatIf:$WhatIfPreference
Set-ClimbAssignment -Collection 'deviceManagement/deviceShellScripts' -Id $scriptId -Name $scriptName -Kind shellScript -Targets $targets -WhatIf:$WhatIfPreference

if ($DownloadOnly) { Write-ClimbStep 'Done (download only).'; return }

# 2. Desktop picture profile
$profileUuid = '6b1d4f2e-6f0a-4c39-9a51-3c1e7c1a2701'   # fixed so updates replace the same profile on the Mac
$payloadUuid = '6b1d4f2e-6f0a-4c39-9a51-3c1e7c1a2702'
$mobileconfig = @"
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>PayloadContent</key>
  <array>
    <dict>
      <key>PayloadType</key><string>com.apple.desktop</string>
      <key>PayloadIdentifier</key><string>com.climb-uk.intune.desktop.picture</string>
      <key>PayloadUUID</key><string>$payloadUuid</string>
      <key>PayloadVersion</key><integer>1</integer>
      <key>PayloadDisplayName</key><string>Climb desktop picture</string>
      <key>override-picture-path</key><string>$([Security.SecurityElement]::Escape($localPath))</string>
    </dict>
  </array>
  <key>PayloadDisplayName</key><string>Climb desktop picture</string>
  <key>PayloadIdentifier</key><string>com.climb-uk.intune.desktop</string>
  <key>PayloadOrganization</key><string>ClimbGroup</string>
  <key>PayloadType</key><string>Configuration</string>
  <key>PayloadUUID</key><string>$profileUuid</string>
  <key>PayloadVersion</key><integer>1</integer>
  <key>PayloadScope</key><string>System</string>
</dict>
</plist>
"@

$profileName = Get-ClimbName 'macOS - Desktop picture'
$profileBody = @{
    '@odata.type'     = '#microsoft.graph.macOSCustomConfiguration'
    displayName       = $profileName
    description       = "Enforces $localPath as the desktop picture. Managed by 21-macOS-Wallpaper.ps1."
    payloadName       = 'Climb desktop picture'
    payloadFileName   = 'climb-desktop.mobileconfig'
    payload           = ConvertTo-ClimbBase64 $mobileconfig
    deploymentChannel = 'deviceChannel'
    roleScopeTagIds   = @('0')
}
$profileId = Set-ClimbObject -Collection 'deviceManagement/deviceConfigurations' -Name $profileName -Body $profileBody -WhatIf:$WhatIfPreference
Set-ClimbAssignment -Collection 'deviceManagement/deviceConfigurations' -Id $profileId -Name $profileName -Kind deviceConfiguration -Targets $targets -WhatIf:$WhatIfPreference

Write-ClimbStep 'Done. If the profile lands before the download, the desktop turns grey until the script has run; it fixes itself at the next run.'
