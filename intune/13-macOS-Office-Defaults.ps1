<#
.SYNOPSIS
    Makes a Climb brand the default for new blank Word, Excel and PowerPoint files on Macs.

.DESCRIPTION
    Creates or updates an Intune macOS shell script called "Climb - macOS - Office brand defaults".
    It runs as root once a day and calls
    /Library/Application Support/Climb/Templates/set-climb-defaults.sh --brand <Brand>, which,
    for every person on the Mac:

      - Word: puts the brand letterhead Normal.dotm in place (the old one is kept as
        Normal-before-Climb.dotm), so a new blank document opens on the letterhead.
      - Excel: puts Book.xltx in the Start-up/Excel folder, so new workbooks use the brand theme.
      - PowerPoint: puts the brand colours and fonts in Default Theme.thmx.

    Each person is set once per templates version and brand, so their own later changes stay.
    People whose Word is open, or who have never opened Office, are picked up on a later run.
    Needs 11-macOS-Templates.ps1 with templates package 1.3.0 or later.

.PARAMETER Brand
    ClimbGroup (default), ClimbUK or Climb27.
.PARAMETER Target
    AllDevices (default), AllUsers, Group or None.
.PARAMETER GroupName
    Entra group name(s) when -Target Group.

.EXAMPLE
    pwsh ./13-macOS-Office-Defaults.ps1 -WhatIf
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [ValidateSet('ClimbUK', 'ClimbGroup', 'Climb27')][string]$Brand = 'ClimbGroup',
    [ValidateSet('AllDevices', 'AllUsers', 'Group', 'None')][string]$Target = 'AllDevices',
    [string[]]$GroupName,
    [string]$TenantId,
    [switch]$UseDeviceCode
)

$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'ClimbIntune.psm1') -Force
Connect-ClimbGraph -TenantId $TenantId -UseDeviceCode:$UseDeviceCode

$lines = @(
    '#!/bin/bash'
    '# Climb Office brand defaults for macOS. Generated by 13-macOS-Office-Defaults.ps1.'
    'set -uo pipefail'
    'LOG="/Library/Logs/Climb/office-defaults.log"'
    'mkdir -p "$(dirname "$LOG")"'
    'exec >>"$LOG" 2>&1'
    'SCRIPT="/Library/Application Support/Climb/Templates/set-climb-defaults.sh"'
    'echo "$(date -u +%FT%TZ) start"'
    'if [ ! -x "$SCRIPT" ]; then echo "Climb templates 1.3.0 or later not installed yet"; exit 0; fi'
    "/bin/bash `"`$SCRIPT`" --brand '$Brand'"
)
$script = ($lines -join "`n") + "`n"

$name = Get-ClimbName 'macOS - Office brand defaults'
$body = @{
    '@odata.type'               = '#microsoft.graph.deviceShellScript'
    displayName                 = $name
    description                 = "New blank Word documents open on the $Brand letterhead; new workbooks and decks use the $Brand theme and fonts. Log: /Library/Logs/Climb/office-defaults.log. Managed by 13-macOS-Office-Defaults.ps1."
    fileName                    = 'climb-office-defaults.sh'
    scriptContent               = ConvertTo-ClimbBase64 $script
    runAsAccount                = 'system'
    executionFrequency          = 'P1D'
    retryCount                  = 3
    blockExecutionNotifications = $true
    roleScopeTagIds             = @('0')
}

$id = Set-ClimbObject -Collection 'deviceManagement/deviceShellScripts' -Name $name -Body $body -WhatIf:$WhatIfPreference
$targets = Get-ClimbAssignmentTargets -Target $Target -GroupName $GroupName
Set-ClimbAssignment -Collection 'deviceManagement/deviceShellScripts' -Id $id -Name $name -Kind shellScript -Targets $targets -WhatIf:$WhatIfPreference

Write-ClimbStep 'Done. Macs run it within about 8 hours of their next check-in, then daily.'
