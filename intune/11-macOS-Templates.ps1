<#
.SYNOPSIS
    Deploys the brand fonts and the Word, Excel and PowerPoint templates to Macs.

.DESCRIPTION
    Creates or updates an Intune macOS shell script (Devices > macOS > Scripts) called
    "Climb - macOS - Brand fonts and Office templates". It runs as root once a day:
    when the installed version is not the expected one, it downloads
    Climb-Templates-<version>.zip, checks its SHA-256 and runs
    macos/install-climb-templates.sh, which puts the fonts in /Library/Fonts and the
    templates where Word, Excel and PowerPoint show them under File > New from Template.

    Re-run this script after a new templates release; Macs update themselves at the next run.
    Needs the Intune management agent on the Macs (installed automatically with the first
    shell script).

.PARAMETER TemplatesVersion
    Package version, for example 1.2.2. Default: the latest templates release.
.PARAMETER IncludeVideo
    Also install the DaVinci Resolve and Premiere Pro files.
.PARAMETER Target
    AllDevices (default), AllUsers, Group or None.
.PARAMETER GroupName
    Entra group name(s) when -Target Group.

.EXAMPLE
    pwsh ./11-macOS-Templates.ps1 -WhatIf
#>
[CmdletBinding(SupportsShouldProcess)]
param(
    [string]$TemplatesVersion,
    [switch]$IncludeVideo,
    [ValidateSet('AllDevices', 'AllUsers', 'Group', 'None')][string]$Target = 'AllDevices',
    [string[]]$GroupName,
    [string]$TenantId,
    [switch]$UseDeviceCode
)

$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'ClimbIntune.psm1') -Force
Connect-ClimbGraph -TenantId $TenantId -UseDeviceCode:$UseDeviceCode

$release = Get-ClimbTemplatesRelease -Version $TemplatesVersion
Write-ClimbStep "Templates $($release.Version): $($release.Url)"

$skip = if ($IncludeVideo) { '' } else { '--skip-video' }
# Shell script body. LF line endings matter on macOS, so build it from an array.
$lines = @(
    '#!/bin/bash'
    '# Climb brand templates for macOS. Generated by 11-macOS-Templates.ps1.'
    'set -euo pipefail'
    "VERSION='$($release.Version)'"
    "URL='$($release.Url)'"
    "SHA256='$($release.Sha256)'"
    'MARKER="/Library/Application Support/Climb/Templates/VERSION"'
    'LOG="/Library/Logs/Climb/intune-templates.log"'
    'mkdir -p "$(dirname "$LOG")"'
    'exec >>"$LOG" 2>&1'
    'echo "$(date -u +%FT%TZ) checking Climb templates $VERSION"'
    'if [ -f "$MARKER" ] && [ "$(head -n1 "$MARKER")" = "$VERSION" ]; then'
    '  echo "already installed"; exit 0'
    'fi'
    'WORK="$(mktemp -d /tmp/climb-templates.XXXXXX)"'
    'trap ''rm -rf "$WORK"'' EXIT'
    'curl -fsSL --retry 3 -o "$WORK/pkg.zip" "$URL"'
    'GOT="$(shasum -a 256 "$WORK/pkg.zip" | awk ''{print $1}'')"'
    'if [ "$GOT" != "$SHA256" ]; then echo "checksum mismatch: $GOT"; exit 1; fi'
    'ditto -x -k "$WORK/pkg.zip" "$WORK"'
    "/bin/bash `"`$WORK/Climb-Templates-`$VERSION/macos/install-climb-templates.sh`" $skip"
    'echo "installed $VERSION"'
)
$script = ($lines -join "`n") + "`n"

$name = Get-ClimbName 'macOS - Brand fonts and Office templates'
$body = @{
    '@odata.type'               = '#microsoft.graph.deviceShellScript'
    displayName                 = $name
    description                 = "Installs Montserrat and Open Sans and the ClimbUK, ClimbGroup and Climb27 Office templates (package $($release.Version)). Log: /Library/Logs/Climb/intune-templates.log. Managed by 11-macOS-Templates.ps1."
    fileName                    = 'climb-templates.sh'
    scriptContent               = ConvertTo-ClimbBase64 $script
    runAsAccount                = 'system'
    executionFrequency          = 'P1D'
    retryCount                  = 3
    blockExecutionNotifications = $true
    roleScopeTagIds             = @('0')
}

$id = Set-ClimbObject -Collection 'deviceManagement/deviceShellScripts' -Name $name -Body $body -WhatIf:$WhatIfPreference
$targets = Get-ClimbAssignmentTargets -Target $Target -GroupName $GroupName
Set-ClimbAssignment -Collection 'deviceManagement/deviceShellScripts' -Id $id -Name $name -Kind shellScript -Targets $targets -WhatIf:$WhatIfPreference

Write-ClimbStep 'Done. Macs run it within about 8 hours of their next check-in, then daily.'
